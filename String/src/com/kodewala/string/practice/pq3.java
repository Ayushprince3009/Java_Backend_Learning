package com.kodewala.string.practice;

public class pq3 {
	public static void main(String[] args) {
		String str1 = "hdfsdfjksd";
		String str2 = "hsufhdlf";
		
		System.out.println(str1 == str2);
		System.out.println(str1.equals(str2));
		
		String str11 = "ayushSS";
		String str21 = "ayushss";
		
		System.out.println(str11 == str21);
		System.out.println(str11.equals(str21));
		
		System.out.println(str11.equalsIgnoreCase(str21));
	}
	
	
}
